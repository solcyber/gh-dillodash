// Command gen-denylist writes internal/hygiene/denylist.txt from the
// maintainers' plaintext term list, keyed by $DILLODASH_HYGIENE_KEY:
//
//	DILLODASH_HYGIENE_KEY="$(<read the key>)" \
//	  go run ./internal/hygiene/cmd/gen-denylist -terms /path/to/private-terms.txt \
//	  > internal/hygiene/denylist.txt
//
// The term list is one term per line (a word, a hyphenated or dotted
// name, a path, or a phrase of up to four words); blank lines and lines
// starting with # are skipped. It never belongs in this repository.
//
// With -hash it reads terms from stdin instead and prints each one's
// hash, for an exemption in the hygiene test.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/solcyber/gh-dillodash/internal/hygiene"
)

func main() {
	terms := flag.String("terms", "", "the plaintext term list (one per line)")
	hashOnly := flag.Bool("hash", false, "hash the terms on stdin, one per line, and print them")
	flag.Parse()
	key := strings.TrimSpace(os.Getenv(hygiene.KeyEnv))
	if key == "" {
		fail("%s is not set", hygiene.KeyEnv)
	}
	k := hygiene.Key(key)
	if *hashOnly {
		for _, t := range read(os.Stdin) {
			fmt.Println(hygiene.Hash(k, t))
		}
		return
	}
	if *terms == "" {
		fail("-terms PATH is required")
	}
	f, err := os.Open(*terms)
	if err != nil {
		fail("%v", err)
	}
	defer f.Close()
	seen := map[string]bool{}
	var out []string
	for _, t := range read(f) {
		h := hygiene.Hash(k, t)
		if !seen[h] {
			seen[h] = true
			out = append(out, h)
		}
	}
	sort.Strings(out)
	fmt.Println("# The hygiene denylist: HMAC-SHA256 of each normalized private term,")
	fmt.Println("# keyed by $" + hygiene.KeyEnv + ". Generated by internal/hygiene/cmd/gen-denylist")
	fmt.Println("# from the maintainers' term list; regenerate it, never edit it by hand.")
	for _, h := range out {
		fmt.Println(h)
	}
}

func read(r io.Reader) []string {
	var out []string
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		t := hygiene.Normalize(sc.Text())
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		out = append(out, t)
	}
	if err := sc.Err(); err != nil {
		fail("%v", err)
	}
	return out
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-denylist: "+format+"\n", args...)
	os.Exit(2)
}
